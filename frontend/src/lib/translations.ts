export type TranslationKey = keyof typeof translations.en;

/** Look up a translation string for the given locale, falling back to English. */
export function t(locale: Locale, key: TranslationKey): string {
  return (translations[locale] as Record<string, string>)[key] ?? translations.en[key];
}

/**
 * Look up a translation string and replace `{placeholder}` tokens.
 * e.g. ti('en', 'welcomeBack', { firstName: 'Alice' }) → "Welcome back, Alice!"
 */
export function ti(locale: Locale, key: TranslationKey, vars: Record<string, string>): string {
  let str = t(locale, key);
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

/** Return a localised count string, e.g. "3 clubs" or "1 Veranstaltung". */
export function tc(locale: Locale, count: number, singular: TranslationKey, plural: TranslationKey): string {
  const word = t(locale, count === 1 ? singular : plural);
  // Chinese already embeds the number word inside the noun phrase
  if (locale === 'zh') return `${count}${word}`;
  return `${count} ${word}`;
}
